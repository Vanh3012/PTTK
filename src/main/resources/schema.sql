CREATE SEQUENCE IF NOT EXISTS customerSeq START WITH 11;
CREATE SEQUENCE IF NOT EXISTS supplierSeq START WITH 11;
CREATE SEQUENCE IF NOT EXISTS productSeq START WITH 11;
CREATE SEQUENCE IF NOT EXISTS invoiceSeq START WITH 11;
CREATE TABLE IF NOT EXISTS tblMember9 (
 memberId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fullName VARCHAR(100) NOT NULL, phone VARCHAR(20) NOT NULL UNIQUE,
 email VARCHAR(120) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL, address VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS tblCustomer9 (
 customerId VARCHAR(20) PRIMARY KEY, memberId INT NOT NULL UNIQUE REFERENCES tblMember9(memberId), registrationDate DATE NOT NULL
);
CREATE TABLE IF NOT EXISTS tblStaff9 (
 staffId VARCHAR(20) PRIMARY KEY, memberId INT NOT NULL UNIQUE REFERENCES tblMember9(memberId), position VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS tblSupplier9 (
 supplierId VARCHAR(20) PRIMARY KEY, name VARCHAR(255) NOT NULL, address VARCHAR(255) NOT NULL,
 phone VARCHAR(20) NOT NULL, status VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS tblCategory9 (
 categoryId VARCHAR(20) PRIMARY KEY, categoryName VARCHAR(100) NOT NULL, description CLOB
);
CREATE TABLE IF NOT EXISTS tblProduct9 (
 productId VARCHAR(20) PRIMARY KEY, productName VARCHAR(255) NOT NULL, brand VARCHAR(100) NOT NULL,
 model VARCHAR(100) NOT NULL, origin VARCHAR(100) NOT NULL, unit VARCHAR(30) NOT NULL,
 listPrice DECIMAL(18,2) NOT NULL CHECK(listPrice > 0), stockQuantity INT NOT NULL CHECK(stockQuantity >= 0),
 warrantyPeriod INT NOT NULL CHECK(warrantyPeriod >= 0), warrantyRequired BOOLEAN NOT NULL,
 description CLOB, status VARCHAR(30) NOT NULL, categoryId VARCHAR(20) NOT NULL REFERENCES tblCategory9(categoryId)
);
CREATE TABLE IF NOT EXISTS tblProductImage9 (
 imageId VARCHAR(20) PRIMARY KEY, imageUrl CLOB, productId VARCHAR(20) NOT NULL REFERENCES tblProduct9(productId)
);
CREATE TABLE IF NOT EXISTS tblImportInvoice9 (
 importInvoiceId VARCHAR(20) PRIMARY KEY, importDate DATE NOT NULL, totalAmount DECIMAL(18,2) NOT NULL CHECK(totalAmount > 0),
 supplierId VARCHAR(20) NOT NULL REFERENCES tblSupplier9(supplierId), warehouseStaffId VARCHAR(20) NOT NULL REFERENCES tblStaff9(staffId)
);
CREATE TABLE IF NOT EXISTS tblImportInvoiceDetail9 (
 importInvoiceId VARCHAR(20) REFERENCES tblImportInvoice9(importInvoiceId), productId VARCHAR(20) REFERENCES tblProduct9(productId),
 quantity INT NOT NULL CHECK(quantity > 0), unitPrice DECIMAL(18,2) NOT NULL CHECK(unitPrice > 0),
 PRIMARY KEY(importInvoiceId, productId)
);
